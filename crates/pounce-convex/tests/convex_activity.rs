//! Activity classification on the convex arm, and the rule it is easiest to
//! misread.
//!
//! # Why this file exists
//!
//! The convex arm had one boolean weak-activity screen against a fixed relative
//! threshold and two flat index lists — no `AMBIGUOUS`, no μ-scaling, no
//! statuses. It now runs `pounce_sens_core::activity_kernel`, the same decision
//! the NLP arm makes, so the two arms cannot drift on what a kink is. This file
//! guards the *derivation* that feeds it, which is the half that genuinely
//! differs between arms and so the half nothing else checks.
//!
//! # The rule this file exists to state as a test
//!
//! `AMBIGUOUS` is **not** "probably not a kink". The cheap curvature a
//! classifier has to hand is the Hessian diagonal (for a variable) or the
//! curvature along the row's own gradient (for a row). The multiplier is
//! generated by the curvature *reduced* along that coordinate — what is left
//! after the other free coordinates re-optimize. So the ratio is
//! `reduced/diagonal`, which equals 1 only when the coordinate is **decoupled**,
//! and a genuine kink on a coupled coordinate lands in `AMBIGUOUS` at any
//! tolerance.
//!
//! That inference — ambiguous, therefore no kink — is what shipped gh#763 on the
//! NLP arm. `an_ambiguous_verdict_does_not_mean_no_kink` builds the same trap
//! here and asserts the classifier falls into it, so the limitation is a pinned
//! property rather than a footnote someone can skip.
//!
//! Note what that test does **not** claim: that the classifier is wrong. It is
//! answering the question it was asked, cheaply and correctly. The error would
//! be a caller reading the answer as a different question's.
//!
//! # What this file is NOT evidence about
//!
//! - **A reduced-curvature refinement.** The NLP arm answers the coupled case
//!   with `reduced_activity` / `reduced_row_activity`, one back-solve per index.
//!   The convex arm has no such accessor yet; this file pins the gap rather than
//!   closing it.
//! - **Scale invariance.** Every fixture here is unit-scaled. The convex arm
//!   still has no scale-invariance leg.
//! - **Agreement with the NLP arm's numbers.** Both call the same kernel, but
//!   `μ` here is the *achieved* complementarity rather than the barrier
//!   parameter the last iteration ran at, so the two agree on bands, not on bits
//!   — see `the_mu_is_the_achieved_complementarity`.
//!
//! # Mutation evidence
//!
//! Each row was **run**, compile-checked, with `--no-fail-fast`:
//!
//! | mutation | red here |
//! |---|---|
//! | a variable's `Σ` drops the upper-bound term (`z_ub/s_ub`) | `an_upper_bound_is_classified_from_its_own_side`, `a_held_bound_a_slack_bound_and_a_free_variable_are_told_apart` |
//! | a row's `q` and `Σ` skip the `‖∇g‖²` weighting | `a_row_classification_is_unmoved_by_rescaling_the_row` |
//! | the curvature floor is `0.0` | `a_flat_direction_is_unidentified_not_inactive` |
//!
//! The second row is not hypothetical: the first draft of this module divided
//! `Σ` by `‖∇g‖⁴` and left `q` un-normalized, which leaves the verdict scaling
//! as `c⁻⁸` under a row rescale. `a_row_classification_is_unmoved_by_rescaling_
//! the_row` caught it before the code was committed, which is the only reason
//! it is a footnote rather than an entry in this repository's defect history.

use pounce_convex::QpOptions;
use pounce_convex::ipm::solve_qp_ipm;
use pounce_convex::qp::{QpProblem, QpStatus, Triplet};
use pounce_convex::sensitivity::QpSensitivity;
use pounce_feral::FeralSolverInterface;
use pounce_linsol::SparseSymLinearSolverInterface;
use pounce_sens_core::activity_kernel::{
    AMBIGUOUS, INACTIVE, STRONGLY_ACTIVE, UNBOUNDED, UNIDENTIFIED, WEAKLY_ACTIVE,
};

fn backend() -> Box<dyn SparseSymLinearSolverInterface> {
    Box::new(FeralSolverInterface::new())
}

fn tri(row: usize, col: usize, val: f64) -> Triplet {
    Triplet { row, col, val }
}

fn solved(prob: &QpProblem) -> QpSensitivity {
    let opts = QpOptions::default();
    let sol = solve_qp_ipm(prob, &opts, backend);
    assert_eq!(sol.status, QpStatus::Optimal, "fixture must solve");
    match QpSensitivity::build(prob, &sol, &opts, 1e-7, backend) {
        Ok(s) => s,
        Err(e) => panic!("fixture must build, got {e:?}"),
    }
}

fn status_name(s: i8) -> &'static str {
    match s {
        UNBOUNDED => "UNBOUNDED",
        INACTIVE => "INACTIVE",
        WEAKLY_ACTIVE => "WEAKLY_ACTIVE",
        STRONGLY_ACTIVE => "STRONGLY_ACTIVE",
        AMBIGUOUS => "AMBIGUOUS",
        UNIDENTIFIED => "UNIDENTIFIED",
        _ => "other",
    }
}

