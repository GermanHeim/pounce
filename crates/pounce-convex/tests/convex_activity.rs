/// **A genuine kink on a coupled coordinate reads `AMBIGUOUS`.**
///
/// Two fixtures, same kink, differing only in whether the kinked coordinate is
/// coupled to another through the Hessian. Decoupled, the ratio is
/// `reduced/diagonal = 1` and the kink is certified `WEAKLY_ACTIVE`. Coupled,
/// the reduced curvature is smaller than the diagonal, the ratio moves off 1,
/// and the same kink lands in `AMBIGUOUS`.
///
/// The second verdict is not a bug — it is the classifier answering the cheap
/// question honestly. The bug would be a caller concluding "ambiguous, so no
/// kink", which is precisely what gh#763 was. Asserting that the two fixtures
/// **land in different classes** is what makes this evidence rather than
/// decoration: it shows the class tracks coupling, not kink-ness.
#[test]
fn an_ambiguous_verdict_does_not_mean_no_kink() {
    // A kink: the bound on x₀ is active with a multiplier vanishing alongside
    // its slack. `coupling` puts an off-diagonal P entry between x₀ and x₁.
    let make = |coupling: f64| {
        let mut p = vec![tri(0, 0, 1.0), tri(1, 1, 1.0)];
        if coupling != 0.0 {
            p.push(tri(1, 0, coupling)); // lower triangle
        }
        QpProblem {
            n: 2,
            p_lower: p,
            c: vec![0.0, 0.0],
            a: vec![tri(0, 0, 1.0), tri(0, 1, 1.0)],
            b: vec![1.0],
            g: vec![],
            h: vec![],
            // x₀'s lower bound sits exactly where the unconstrained optimum
            // puts it, so slack and multiplier vanish together.
            lb: vec![0.5, f64::NEG_INFINITY],
            ub: vec![f64::INFINITY; 2],
        }
    };

    let decoupled = solved(&make(0.0)).activity();
    let coupled = solved(&make(0.97)).activity();

    let a = decoupled.var_status[0];
    let b = coupled.var_status[0];

    // The precondition that makes the rest meaningful: the two fixtures take
    // DIFFERENT branches. Without this the test says nothing about coupling.
    assert_ne!(
        a,
        b,
        "the decoupled and coupled kinks must land in different classes, or \
         this fixture pair is not exercising the rule at all: both {} \
         (ratios {} and {})",
        status_name(a),
        decoupled.var_ratio[0],
        coupled.var_ratio[0]
    );
    assert_eq!(
        a,
        WEAKLY_ACTIVE,
        "a DECOUPLED kink has ratio ≈ 1 and is certified weakly active; got {} \
         with ratio {}",
        status_name(a),
        decoupled.var_ratio[0]
    );
    assert_eq!(
        b,
        AMBIGUOUS,
        "the SAME kink, coupled, reads ambiguous — because the ratio is \
         reduced/diagonal, not because the kink went away. Reading this as \
         'no kink' is the gh#763 error. Got {} with ratio {}",
        status_name(b),
        coupled.var_ratio[0]
    );
}

/// The ambiguity above is **μ-independent**: it is a property of the coupling,
/// not of how tightly the problem was solved. Someone who assumes a tighter
/// solve will resolve it needs this stated as a measurement.
#[test]
fn the_coupled_ambiguity_does_not_resolve_with_a_tighter_solve() {
    let prob = QpProblem {
        n: 2,
        p_lower: vec![tri(0, 0, 1.0), tri(1, 1, 1.0), tri(1, 0, 0.97)],
        c: vec![0.0, 0.0],
        a: vec![tri(0, 0, 1.0), tri(0, 1, 1.0)],
        b: vec![1.0],
        g: vec![],
        h: vec![],
        lb: vec![0.5, f64::NEG_INFINITY],
        ub: vec![f64::INFINITY; 2],
    };
    for tol in [1e-8, 1e-10, 1e-12] {
        let opts = QpOptions {
            tol,
            ..Default::default()
        };
        let sol = solve_qp_ipm(&prob, &opts, backend);
        assert_eq!(sol.status, QpStatus::Optimal);
        let Ok(sens) = QpSensitivity::build(&prob, &sol, &opts, 1e-7, backend) else {
            panic!("must build at tol {tol}");
        };
        let rep = sens.activity();
        assert_eq!(
            rep.var_status[0], AMBIGUOUS,
            "at tol {tol} the coupled kink still reads ambiguous (ratio {}, \
             mu {}) — the ratio is reduced/diagonal, which does not move with μ",
            rep.var_ratio[0], rep.mu
        );
    }
}

// ---------------------------------------------------------------------------
// What `mu` is, stated so a cross-arm comparison is not written against it.
// ---------------------------------------------------------------------------

/// The report's `μ` is the achieved complementarity, which is what makes it
/// derivable without a barrier iterate — and what makes it the wrong thing to
/// demand bit-agreement on with the NLP arm.
#[test]
fn the_mu_is_the_achieved_complementarity() {
    let prob = QpProblem {
        n: 2,
        p_lower: vec![tri(0, 0, 1.0), tri(1, 1, 1.0)],
        c: vec![-4.0, 0.0],
        a: vec![tri(0, 0, 1.0), tri(0, 1, 1.0)],
        b: vec![1.0],
        g: vec![],
        h: vec![],
        lb: vec![0.0, f64::NEG_INFINITY],
        ub: vec![0.5, f64::INFINITY],
    };
    let sens = solved(&prob);
    let rep = sens.activity();
    assert_eq!(
        rep.mu,
        sens.duality_measure(),
        "the report bands against exactly `duality_measure()`; if these ever \
         diverge, a caller reading one and reasoning about the other is wrong"
    );
}
