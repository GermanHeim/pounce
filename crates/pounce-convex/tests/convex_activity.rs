/// A row's classification must not change when the row is multiplied through by
/// a constant. That is what the `‖∇g‖⁴` normalization buys, and without it the
/// verdict moves with an arbitrary modelling choice.
#[test]
fn a_row_classification_is_unmoved_by_rescaling_the_row() {
    let make = |scale: f64| QpProblem {
        n: 2,
        p_lower: vec![tri(0, 0, 1.0), tri(1, 1, 1.0)],
        c: vec![-1.0, -1.0],
        a: vec![],
        b: vec![],
        g: vec![tri(0, 0, scale), tri(0, 1, scale)],
        h: vec![0.5 * scale],
        lb: vec![f64::NEG_INFINITY; 2],
        ub: vec![f64::INFINITY; 2],
    };
    let plain = solved(&make(1.0)).activity();
    let scaled = solved(&make(1000.0)).activity();

    assert_eq!(
        plain.row_status[0],
        scaled.row_status[0],
        "scaling a row by 1000 must not change what it is doing: {} vs {} \
         (ratios {} vs {})",
        status_name(plain.row_status[0]),
        status_name(scaled.row_status[0]),
        plain.row_ratio[0],
        scaled.row_ratio[0]
    );
    // The *band* is the claim, and the raw ratio deliberately is not.
    //
    // Measured: 1.2e9 against 1.4e11 for the two scalings above. The formula is
    // exactly invariant — `Σ·‖∇g‖²` and `∇gᵀP∇g/‖∇g‖²` each cancel the `c`
    // powers — but at a *hard-active* row `Σ = z/s` is dominated by how close to
    // zero the solve drove `s`, and that is set by the absolute tolerance, which
    // rescaling moves. So the ratio's magnitude there reports solver noise, and
    // asserting on it would be asserting on the stopping rule.
    //
    // Both extremes have this property: at an inactive row it is `z` rather
    // than `s` that is noise. Only a weakly-active row carries an `O(1)` ratio
    // that means something, which is why the invariance claim in this file is
    // about which class the row lands in.
    assert!(
        plain.row_ratio[0] > 1e1 && scaled.row_ratio[0] > 1e1,
        "both must still be far above the band — the shared verdict is not an \
         accident of both landing in the same wrong place: {} and {}",
        plain.row_ratio[0],
        scaled.row_ratio[0]
    );
}

