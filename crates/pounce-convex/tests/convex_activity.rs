/// A bound that holds its coordinate classifies strongly active; one that does
/// nothing classifies inactive; one with no finite bound is not classified.
#[test]
fn a_held_bound_a_slack_bound_and_a_free_variable_are_told_apart() {
    // `min ½‖x‖² − 4x₀ + x₁ + x₂  s.t.  x₀ + x₁ + x₂ = 1`,
    // x₀ ∈ [0, 0.5] (upper bound binds hard), x₁ ≥ 0 (binds), x₂ free.
    let prob = QpProblem {
        n: 3,
        p_lower: vec![tri(0, 0, 1.0), tri(1, 1, 1.0), tri(2, 2, 1.0)],
        c: vec![-4.0, 1.0, 0.0],
        a: vec![tri(0, 0, 1.0), tri(0, 1, 1.0), tri(0, 2, 1.0)],
        b: vec![1.0],
        g: vec![],
        h: vec![],
        lb: vec![0.0, 0.0, f64::NEG_INFINITY],
        ub: vec![0.5, f64::INFINITY, f64::INFINITY],
    };
    let rep = solved(&prob).activity();

    assert_eq!(
        rep.var_status[0],
        STRONGLY_ACTIVE,
        "x0 is pinned at its upper bound, got {}",
        status_name(rep.var_status[0])
    );
    assert_eq!(
        rep.var_status[2],
        UNBOUNDED,
        "x2 has no finite bound, got {}",
        status_name(rep.var_status[2])
    );
    assert!(
        rep.mu > 0.0 && rep.mu < 1e-6,
        "the report carries the achieved complementarity, got {}",
        rep.mu
    );
}

/// A variable's `Σ` sums both sides, so an *upper* bound is classified from its
/// own slack and multiplier rather than from the lower one's.
#[test]
fn an_upper_bound_is_classified_from_its_own_side() {
    // x₀ ∈ [0, 0.5] with the objective pushing it up: the UPPER bound is what
    // holds it, and the lower one is slack.
    let prob = QpProblem {
        n: 2,
        p_lower: vec![tri(0, 0, 1.0), tri(1, 1, 1.0)],
        c: vec![-4.0, 0.0],
        a: vec![tri(0, 0, 1.0), tri(0, 1, 1.0)],
        b: vec![1.0],
        g: vec![],
        h: vec![],
        lb: vec![0.0, f64::NEG_INFINITY],
        ub: vec![0.5, f64::INFINITY],
    };
    let rep = solved(&prob).activity();
    assert_eq!(
        rep.var_status[0],
        STRONGLY_ACTIVE,
        "the upper bound holds x0; dropping the `z_ub/s_ub` term from Σ would \
         report it inactive. Got {} with Σ = {}",
        status_name(rep.var_status[0]),
        rep.var_sigma[0]
    );
}

/// A coordinate with no curvature has no bound question to answer: the
/// classifier says so rather than guessing.
#[test]
fn a_flat_direction_is_unidentified_not_inactive() {
    // `min −x₀ s.t. x₀ + x₁ = 1, 0 ≤ x₀ ≤ 1`, with NO quadratic term on x₀.
    let prob = QpProblem {
        n: 2,
        p_lower: vec![tri(1, 1, 1.0)],
        c: vec![-1.0, 0.0],
        a: vec![tri(0, 0, 1.0), tri(0, 1, 1.0)],
        b: vec![1.0],
        g: vec![],
        h: vec![],
        lb: vec![0.0, f64::NEG_INFINITY],
        ub: vec![1.0, f64::INFINITY],
    };
    let rep = solved(&prob).activity();
    assert_eq!(
        rep.var_status[0],
        UNIDENTIFIED,
        "x0 carries no curvature, so the ratio Σ/q is not a question the \
         classifier can answer; got {}",
        status_name(rep.var_status[0])
    );
}

